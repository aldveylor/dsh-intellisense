import { test } from 'node:test';
import assert from 'node:assert/strict';
import { Context } from '@deepseek-ai/cordis';
import type { Agent } from '@deepseek-ai/dsh-agent';
import { createScope } from '@deepseek-ai/dsh-scope';
import * as presentation from '../../src/integration/presentation.js';
import { NamespaceComponent } from '../../src/namespace/component.js';
import { SemanticRegistry } from '../../src/registry/registry.js';
import { ProfileSessions } from '../../src/registry/profiles.js';
import { MemoryStore } from '../../src/storage/store.js';

test('only an explicit Intellisense scope enables namespace configuration and descendants inherit it', async () => {
    const ctx = new Context();
    const store = new MemoryStore();
    const registry = new SemanticRegistry(store);
    const component = new NamespaceComponent(ctx, registry, new ProfileSessions(registry, store), []);
    const standard = createScope(ctx, {});
    const intellisenseKey = {};
    const intellisense = createScope(ctx, intellisenseKey);
    const child = createScope(ctx, {}, { parent: intellisenseKey });
    const standardAgent = { id: 'standard', ctx: standard.ctx } as Agent;
    assert.equal(component.enabled(standardAgent), false);
    component.registryFor = async () => { throw new Error('Standard mode must not initialize namespaces'); };
    await component.configure(standardAgent);
    const registrations: Context[] = [];
    const presentations: string[] = [];
    ctx.provide('toolsNamespace', { register: (scope: Context) => registrations.push(scope) } as unknown as NamespaceComponent);
    ctx.provide('tools', { presentAs: (mode: string) => presentations.push(mode) } as unknown as Context['tools']);
    const mounted = await intellisense.ctx.plugin(presentation, { mode: 'native', profile: 'Work' });
    assert.equal(registrations.length, 1);
    assert.equal(presentation.presentationFor(registrations[0]!), 'native');
    assert.deepEqual(presentations, ['native']);
    assert.equal(component.enabled({ ctx: intellisense.ctx } as Agent), true);
    assert.equal(component.enabled({ ctx: child.ctx } as Agent), true);
    assert.equal(component.fixedProfile({ ctx: child.ctx } as Agent), 'Work');
    assert.equal(component.enabled(standardAgent), false);
    const override = await child.ctx.plugin(presentation, { mode: 'native' });
    assert.equal(component.fixedProfile({ ctx: child.ctx } as Agent), undefined);
    await override.dispose();
    assert.equal(component.fixedProfile({ ctx: child.ctx } as Agent), 'Work');
    await mounted.dispose();
    assert.equal(component.enabled({ ctx: intellisense.ctx } as Agent), false);
    await child.dispose();
    await intellisense.dispose();
    await standard.dispose();
});
